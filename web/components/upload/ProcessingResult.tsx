"use client";

import { CheckCircle2, Download, RefreshCw, FileSpreadsheet, TrendingUp, ExternalLink, Loader2, ArrowUpRight, AlertTriangle, FileCheck2, BookOpenCheck } from"lucide-react";
import { useEffect, useState } from"react";
import type { ProcessResult, Transaction } from"@/types/billing";
import { Button } from"@/components/ui/Button";
import { Badge } from"@/components/ui/Badge";
import { Alert } from "@/components/ui/Alert";
import { AnalyticsDashboard } from "./AnalyticsDashboard";

interface Props {
  result: ProcessResult & { is_demo?: boolean };
  onReset: () => void;
  hasSheetsAccess?: boolean;

}

const FORMAT_LABELS: Record<string, string> = {
  csv:"Download CSV",
  xlsx:"Download Excel (.xlsx)",
  ofx:"Download OFX (QuickBooks / Tally)",
  qfx:"Download QFX (Quicken)",
  qbo:"Download QBO (QuickBooks)",
  sheets:"Download Google Sheets (CSV)",
};

const FORMAT_EXTENSIONS: Record<string, string> = {
  csv:"csv",
  xlsx:"xlsx",
  ofx:"ofx",
  qfx:"qfx",
  qbo:"qbo",
  sheets:"csv",
};

export function ProcessingResult({ result, onReset, hasSheetsAccess }: Props) {
  const [sheetsExporting, setSheetsExporting] = useState(false);
  const [qbConnected, setQbConnected] = useState(false);
  const [qbPushing, setQbPushing] = useState(false);
  const [qbMsg, setQbMsg] = useState<string | null>(null);

  useEffect(() => {
    fetch("/api/quickbooks/status")
      .then((r) => (r.ok ? r.json() : null))
      .then((d) => setQbConnected(Boolean(d?.connected)))
      .catch(() => {});
  }, []);

  const pushToQuickBooks = async () => {
    const bankAccountId = localStorage.getItem("qb_bank_account_id") ?? "";
    if (!bankAccountId) {
      setQbMsg("Save your QuickBooks bank account ID first (Dashboard → Settings → QuickBooks), then push.");
      return;
    }
    setQbPushing(true);
    setQbMsg(null);
    try {
      const res = await fetch("/api/quickbooks/push", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          bankAccountId,
          transactions: (result.transactions ?? []).map((t) => ({
            date: String(t.date).slice(0, 10),
            description: String(t.description ?? ""),
            amount: typeof t.amount === "number" ? t.amount : 0,
          })),
        }),
      });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error ?? "Push failed");
      setQbMsg(`✓ Sent ${data.created} transactions to QuickBooks${data.failed ? ` — ${data.failed} failed` : ""}.`);
    } catch (e) {
      setQbMsg(e instanceof Error ? e.message : "Push failed");
    }
    setQbPushing(false);
  };

  const downloadReport = () => {
    const r = result.reconciliation;
    const money = (n?: number | null) =>
      n == null ? "—" : n.toLocaleString("en-US", { style: "currency", currency: "USD" });
    const esc = (s: string) =>
      s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
    const rows = (result.transactions ?? [])
      .map(
        (t) =>
          "<tr><td>" + esc(String(t.date ?? "")) + "</td><td>" + esc(String(t.description ?? "")) +
          "</td><td>" + esc(String(t.category ?? "")) + "</td><td style='text-align:right'>" +
          money(typeof t.amount === "number" ? t.amount : null) + "</td></tr>"
      )
      .join("");
    const verdict = !r?.checked
      ? "Balance check not available for this file (the statement did not include running balances)."
      : r.ok
        ? "VERIFIED — the running balance ties out at every step. Opening + every transaction = closing."
        : "WARNING — at least one step in the balance chain does not add up. Review before importing.";
    const html =
      "<!DOCTYPE html><html><head><meta charset='utf-8'><title>Reconciliation Report — " +
      esc(result.file_name ?? "statement") +
      "</title><style>body{font-family:Arial,Helvetica,sans-serif;color:#111;margin:40px;font-size:13px}" +
      "h1{font-size:20px;margin:0 0 4px}h2{font-size:14px;margin:24px 0 8px}" +
      ".muted{color:#666}table{width:100%;border-collapse:collapse;margin-top:8px}" +
      "td,th{border-bottom:1px solid #ddd;padding:6px 8px;text-align:left}th{background:#f4f4f5}" +
      ".box{border:1px solid #ddd;border-radius:8px;padding:14px 16px;margin-top:14px}" +
      ".ok{color:#047857;font-weight:bold}.warn{color:#b45309;font-weight:bold}" +
      "@media print{button{display:none}}</style></head><body>" +
      "<h1>Reconciliation Report</h1>" +
      "<p class='muted'>Generated by Convert Statement · " + new Date().toLocaleString("en-US") + "</p>" +
      "<div class='box'><p><strong>Statement file:</strong> " + esc(result.file_name ?? "—") +
      (result.bank_name ? "<br><strong>Bank:</strong> " + esc(result.bank_name) : "") +
      "<br><strong>Transactions:</strong> " + (r?.transactionCount ?? result.transactions?.length ?? 0) +
      "<br><strong>Opening balance:</strong> " + money(r?.openingBalance) +
      "<br><strong>Closing balance:</strong> " + money(r?.closingBalance) +
      "<br><strong>Net change:</strong> " + money(r?.netChange) + "</p>" +
      "<p class='" + (r?.ok ? "ok" : "warn") + "'>" + verdict + "</p></div>" +
      "<h2>Transactions</h2><table><thead><tr><th>Date</th><th>Description</th><th>Category</th><th style='text-align:right'>Amount</th></tr></thead><tbody>" +
      rows +
      "</tbody></table>" +
      "<p class='muted' style='margin-top:20px'>This report was generated from the converted file. Verify totals against the original bank statement before relying on them for filing.</p>" +
      "<script>window.onload=function(){window.print()}<\/script></body></html>";
    const w = window.open("", "_blank", "width=900,height=700");
    if (w) {
      w.document.write(html);
      w.document.close();
    }
  };

  const [sheetsUrl, setSheetsUrl] = useState<string | null>(null);
  const [sheetsError, setSheetsError] = useState<string | null>(null);



  const exportToSheets = async () => {
    setSheetsExporting(true);
    setSheetsError(null);
    try {
      const res = await fetch("/api/google-sheets/export", {
        method:"POST",
        headers: {"Content-Type":"application/json" },
        body: JSON.stringify({
          fileName: result.file_name,
          transactions: result.transactions,
          bankName: result.bank_name,
        }),
      });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error ??"Export failed.");
      setSheetsUrl(data.url);
    } catch (err: unknown) {
      setSheetsError(err instanceof Error ? err.message :"Export failed.");
    } finally { setSheetsExporting(false); }
  };

  const handleDownload = (fmt: string, url: string) => {
    const ext = FORMAT_EXTENSIONS[fmt] ?? fmt;
    const a = document.createElement("a");
    a.href = url;
    a.download = `${result.file_name.replace(".pdf","")}_transactions.${ext}`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
  };

  return (
    <div className="space-y-4">
      {/* Demo notice */}
      {result.is_demo && (
        <Alert variant="info" title="Sample data">
          This is a demo using a sample bank statement.{""}
          <a href="/signup" className="font-semibold underline hover:no-underline">
            Sign up free
          </a>{""}
          to convert your own bank statements.
        </Alert>
      )}

      {/* Success card */}
      <div className="rounded-2xl border border-emerald-200 dark:border-emerald-800 bg-emerald-50 dark:bg-emerald-900/20 p-5 shadow-sm">
        <div className="flex items-start gap-3">
          <CheckCircle2 className="mt-0.5 h-6 w-6 shrink-0 text-emerald-500 text-emerald-500 dark:text-emerald-400" />
          <div className="min-w-0 flex-1">
            <div className="flex items-center gap-2 flex-wrap">
              <h3 className="font-bold text-zinc-900 dark:text-zinc-200">Processing complete!</h3>
              <Badge variant="success" size="sm" dot>Done</Badge>
            </div>
            <p className="mt-0.5 truncate text-sm text-brand-muted">{result.file_name}</p>
          </div>
        </div>
        {/* Stats row */}
        <div className="mt-4 grid grid-cols-3 gap-3">
          <StatCard label="Pages" value={result.page_count} />
          <StatCard label="Transactions" value={result.transaction_count} />
          <StatCard label="Time" value={`${(result.processing_ms / 1000).toFixed(1)}s`} />
        </div>

        {result.bank_name && (
          <p className="mt-3 text-center text-xs text-brand-muted">
            Detected: <span className="font-semibold text-zinc-600 dark:text-zinc-300">{result.bank_name}</span>
          </p>
        )}

        {/* Billing message */}
        <p className="mt-2 text-center text-xs text-emerald-600 dark:text-emerald-400 font-medium">
          {result.billing.message}
        </p>

        {/* Analytics Dashboard */}
        {result.transactions && result.transactions.length > 0 && (
          <AnalyticsDashboard transactions={result.transactions} />
        )}

        {/* Reconciliation balance check */}
        {result.reconciliation?.checked && (
          result.reconciliation.ok ? (
            <div className="mt-4 flex items-start gap-3 rounded-xl border border-emerald-200 bg-emerald-50 dark:border-emerald-800 dark:bg-emerald-950/40 px-4 py-3">
              <CheckCircle2 className="h-5 w-5 shrink-0 text-emerald-600 dark:text-emerald-400 mt-0.5" />
              <div className="text-sm">
                <p className="font-semibold text-emerald-900 dark:text-emerald-100">Balance verified — this file ties to your statement</p>
                <p className="text-emerald-700 dark:text-emerald-300 mt-0.5">
                  Opening {result.reconciliation.openingBalance?.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}
                  {" → "}closing {result.reconciliation.closingBalance?.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}
                  {" "}across {result.reconciliation.transactionCount} transactions. The running balance checks out at every step, so QuickBooks reconciliation starts from a file that already agrees with the bank.
                </p>
              </div>
            </div>
          ) : (
            <div className="mt-4 flex items-start gap-3 rounded-xl border border-amber-200 bg-amber-50 dark:border-amber-800 dark:bg-amber-950/40 px-4 py-3">
              <AlertTriangle className="h-5 w-5 shrink-0 text-amber-600 dark:text-amber-400 mt-0.5" />
              <div className="text-sm">
                <p className="font-semibold text-amber-900 dark:text-amber-100">Heads up — the running balances don&apos;t fully tie out</p>
                <p className="text-amber-700 dark:text-amber-300 mt-0.5">
                  At least one step in the statement&apos;s balance chain doesn&apos;t add up. That usually means a missing or duplicated transaction in the source statement. Review the transactions below before importing, so the problem doesn&apos;t land in QuickBooks.
                </p>
              </div>
            </div>
          )
        )}

        {/* Downloads */}
        {Object.keys(result.export_urls).length > 0 && (
          <div className="mt-4 space-y-2">
            <p className="text-xs font-semibold uppercase tracking-wider text-brand-muted">Downloads</p>
            {Object.entries(result.export_urls).map(([fmt, url]) => (
              <button
                key={fmt}
                onClick={() => handleDownload(fmt, url)}
                className="flex w-full items-center justify-between rounded-xl bg-zinc-900 hover:bg-zinc-800 active:scale-[0.99] transition-all px-4 py-3 text-sm font-semibold text-white"
              >
                <span className="flex items-center gap-2">
                  <FileSpreadsheet className="h-4 w-4 text-white/80 text-indigo-500 dark:text-indigo-400" />
                  {FORMAT_LABELS[fmt] ?? fmt.toUpperCase()}
                </span>
                <Download className="h-4 w-4 text-white/80 text-emerald-500 dark:text-emerald-400" />
              </button>
            ))}

            {result.locked_formats && result.locked_formats.length > 0 && (
              <div className="rounded-xl border border-violet-200 bg-violet-50 px-4 py-3 text-xs text-violet-800">
                <span className="font-semibold">{result.locked_formats.map(f => FORMAT_LABELS[f] ?? f.toUpperCase()).join(", ")}</span>
                {" "}exports are Pro plan features. <a href="/pricing" className="font-semibold underline">Upgrade to Pro</a> to unlock them — your downloads above are ready.
              </div>
            )}

            {/* Send to QuickBooks (direct connect) */}
            {qbConnected && result.transactions && result.transactions.length > 0 && (
              <div>
                <button
                  onClick={pushToQuickBooks}
                  disabled={qbPushing}
                  className="flex w-full items-center justify-between rounded-xl bg-emerald-600 hover:bg-emerald-500 px-4 py-3 text-sm font-semibold text-white transition-all disabled:opacity-50"
                >
                  <span className="flex items-center gap-2">
                    <BookOpenCheck className="h-4 w-4 text-white/80" />
                    {qbPushing ? "Sending to QuickBooks…" : "Send to QuickBooks"}
                  </span>
                  <ArrowUpRight className="h-4 w-4 text-white/80" />
                </button>
                {qbMsg && <p className="mt-2 text-xs text-brand-muted">{qbMsg}</p>}
              </div>
            )}

            {/* Reconciliation report (printable PDF) */}
            {result.reconciliation?.checked && (
              <button
                onClick={downloadReport}
                className="flex w-full items-center justify-between rounded-xl border border-zinc-300 dark:border-zinc-700 bg-white dark:bg-zinc-900 hover:bg-zinc-50 dark:hover:bg-zinc-800 px-4 py-3 text-sm font-semibold text-zinc-800 dark:text-zinc-100 transition-all"
              >
                <span className="flex items-center gap-2">
                  <FileCheck2 className="h-4 w-4 text-emerald-600 dark:text-emerald-400" />
                  Reconciliation Report (PDF)
                </span>
                <Download className="h-4 w-4 text-zinc-400" />
              </button>
            )}

            {/* Google Sheets export (Pro/Business) */}
            {hasSheetsAccess && (
              sheetsUrl ? (
                <a
                  href={sheetsUrl}
                  target="_blank"
                  rel="noopener noreferrer"
                  className="flex w-full items-center justify-between rounded-xl bg-green-600 hover:bg-green-700 px-4 py-3 text-sm font-semibold text-white transition-all"
                >
                  <span className="flex items-center gap-2">
                    <svg viewBox="0 0 24 24" className="h-4 w-4 fill-white/80"><path d="M6 2h8l6 6v14a2 2 0 01-2 2H6a2 2 0 01-2-2V4a2 2 0 012-2z"/><path d="M14 2l6 6h-6V2z" opacity=".5"/></svg>
                    Open in Google Sheets
                  </span>
                  <ExternalLink className="h-4 w-4 text-white/80 text-cyan-500 dark:text-cyan-400" />
                </a>
              ) : (
                <button
                  onClick={exportToSheets}
                  disabled={sheetsExporting}
                  className="flex w-full items-center justify-between rounded-xl bg-green-50 dark:bg-green-900/20 border border-green-200 dark:border-green-800 hover:bg-green-100 dark:hover:bg-green-900/30 px-4 py-3 text-sm font-semibold text-green-700 dark:text-green-400 transition-all disabled:opacity-50"
                >
                  <span className="flex items-center gap-2">
                    {sheetsExporting
                      ? <Loader2 className="h-4 w-4 animate-spin text-purple-500 dark:text-purple-400" />
                      : <svg viewBox="0 0 24 24" className="h-4 w-4" fill="currentColor"><path d="M6 2h8l6 6v14a2 2 0 01-2 2H6a2 2 0 01-2-2V4a2 2 0 012-2z"/><path d="M14 2l6 6h-6V2z" opacity=".4"/></svg>
                    }
                    {sheetsExporting ?"Exporting to Google Sheets…" :"Export to Google Sheets"}
                  </span>
                  <ExternalLink className="h-4 w-4 opacity-60 text-cyan-500 dark:text-cyan-400" />
                </button>
              )
            )}
            {sheetsError && (
              <p className="text-xs text-red-600 dark:text-red-400 px-1">{sheetsError}</p>
            )}
          </div>
        )}
      </div>

      {/* Transaction preview */}
      {result.transactions.length > 0 && (
        <div className="rounded-2xl border border-brand-border bg-brand-surface overflow-hidden">
          <div className="flex items-center justify-between border-b border-zinc-100 dark:border-zinc-800 px-5 py-3 bg-zinc-50">
            <div className="flex items-center gap-2 text-sm font-semibold text-zinc-900 dark:text-zinc-200">
              <TrendingUp className="h-4 w-4 dark:text-violet-400 text-cyan-500 dark:text-cyan-400" />
              Transaction preview
            </div>
            <Badge variant="default" size="sm">
              {result.transactions.length} of {result.transaction_count}
            </Badge>
          </div>
          <div className="divide-y divide-zinc-100 dark:divide-white/10 font-mono">
            {result.transactions.map((txn: Transaction, i) => (
              <div key={i} className="flex items-center gap-3 px-5 py-2.5 hover:bg-zinc-50 transition-colors">
                <div className="min-w-0 flex-1">
                  <p className="truncate text-xs font-medium text-zinc-900 dark:text-zinc-200">{txn.description}</p>
                  <p className="text-xs text-brand-muted dark:text-brand-muted">
                    {txn.date}{txn.category && ` · ${txn.category}`}
                  </p>
                </div>
                <span className={`shrink-0 text-xs font-bold tabular-nums ${txn.amount >= 0 ?"text-emerald-600 dark:text-emerald-400" :"text-zinc-900 dark:text-zinc-300"}`}>
                  {txn.amount >= 0 ? "+" : "-"}${Math.abs(txn.amount).toFixed(2)}
                </span>
              </div>
            ))}
          </div>
        </div>
      )}

      <Button
        variant="secondary"
        fullWidth
        leftIcon={<RefreshCw className="h-4 w-4 text-rose-500 dark:text-rose-400" />}
        onClick={onReset}
      >
        Process another statement
      </Button>
    </div>
  );
}

function StatCard({ label, value }: { label: string; value: string | number }) {
  return (
    <div className="rounded-xl bg-brand-surface border border-zinc-200 dark:bg-zinc-950 p-3 text-center">
      <p className="text-xl font-bold text-zinc-900 dark:text-zinc-200">{value}</p>
      <p className="text-xs text-brand-muted dark:text-brand-muted">{label}</p>
    </div>
  );
}
